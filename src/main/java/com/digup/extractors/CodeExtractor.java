package com.digup.extractors;

import com.digup.engine.Rules;
import com.digup.model.IndexOptions;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;

/**
 * Source code line stretch chunker and Jupyter Notebook parser.
 */
public final class CodeExtractor {

    public static class Piece {
        public final String text;
        public final int first;
        public final int last;

        public Piece(String text, int first, int last) {
            this.text = text;
            this.first = first;
            this.last = last;
        }
    }

    public static class CodeFile {
        public final List<Piece> pieces;
        public final String title;
        public final String repo;
        public final int lines;
        public final Integer cells;

        public CodeFile(List<Piece> pieces, String title, String repo, int lines, Integer cells) {
            this.pieces = pieces;
            this.title = title;
            this.repo = repo;
            this.lines = lines;
            this.cells = cells;
        }
    }

    private static final Set<String> CLOSERS = Set.of("}", ")", "]", "end", "fi", "done", "esac");

    public static CodeFile read(File file, IndexOptions options) throws IOException {
        String name = file.getName();
        String absPath = file.getAbsolutePath().replace('\\', '/');
        String[] repoAndTitle = resolvePlace(file);
        String repo = repoAndTitle[0];
        String title = repoAndTitle[1];

        if (name.toLowerCase().endsWith(".ipynb")) {
            String json = Files.readString(file.toPath(), StandardCharsets.UTF_8);
            List<String> cells = parseNotebookCells(json);
            StringBuilder combined = new StringBuilder();
            for (String c : cells) combined.append(c).append("\n");
            String text = combined.toString();

            if (text.length() > options.maxCodeBytes) {
                throw new IOException("Notebook exceeds maximum allowed code size");
            }
            check(text, true);

            List<Piece> pieces = chunkCells(cells, options.codeStretch);
            return new CodeFile(pieces, title, repo, countLines(text), cells.size());
        }

        byte[] rawBytes = Files.readAllBytes(file.toPath());
        int prefixCheck = Math.min(8000, rawBytes.length);
        for (int i = 0; i < prefixCheck; i++) {
            if (rawBytes[i] == 0) throw new IOException("Binary file, not text");
        }

        String text = new String(rawBytes, StandardCharsets.UTF_8);
        int extDot = name.lastIndexOf('.');
        String ext = extDot >= 0 ? name.substring(extDot + 1).toLowerCase() : "";
        check(text, Rules.SOURCE_EXTENSIONS.contains(ext));

        List<Piece> pieces = lines(text, options.codeStretch);
        return new CodeFile(pieces, title, repo, countLines(text), null);
    }

    public static void check(String text, boolean source) throws IOException {
        if (text.contains("PRIVATE KEY-----")) {
            throw new IOException("Holds a private key");
        }
        if (!source) return;

        String top = text.length() > 1000 ? text.substring(0, 1000) : text;
        String[] generatedMarks = {
            "DO NOT EDIT", "@generated", "Code generated by", "Autogenerated by", "Generated by the protocol"
        };
        for (String m : generatedMarks) {
            if (top.contains(m)) {
                throw new IOException("Generated by a tool (" + m + ")");
            }
        }

        int lines = Math.max(1, countLines(text));
        int chars = text.length();
        if (chars / lines > 300) {
            for (String line : text.split("\\r?\\n")) {
                if (line.length() > 3000) {
                    throw new IOException("Minified code (" + (chars / lines) + " chars per line)");
                }
            }
        }
    }

    public static int countLines(String text) {
        if (text == null || text.isEmpty()) return 0;
        int count = 0;
        for (int i = 0; i < text.length(); i++) {
            if (text.charAt(i) == '\n') count++;
        }
        return (text.endsWith("\n")) ? count : count + 1;
    }

    public static List<Piece> lines(String text, int size) {
        String[] allLines = text.split("\\r?\\n", -1);
        int count = allLines.length;
        if (count > 0 && allLines[count - 1].isEmpty()) count--;

        int[] offsets = new int[count + 1];
        offsets[0] = 0;
        for (int i = 0; i < count; i++) {
            offsets[i + 1] = offsets[i] + allLines[i].length() + 1;
        }

        List<Piece> pieces = new ArrayList<>();
        int start = 0;
        while (start < count) {
            while (start < count && allLines[start].trim().isEmpty()) {
                start++;
            }
            if (start >= count) break;

            int end = start + 1;
            while (end < count && (offsets[end + 1] - offsets[start] <= size)) {
                end++;
            }

            boolean natural = (end >= count);
            if (!natural) {
                int floor = offsets[start] + (size * 2 / 5);
                Integer cut = null;
                for (int line = end; line > start + 1; line--) {
                    if (offsets[line] < floor) break;
                    if (startsBlock(allLines[line]) && allLines[line - 1].trim().isEmpty()) {
                        cut = line;
                        break;
                    }
                }
                if (cut == null) {
                    for (int line = end; line > start + 1; line--) {
                        if (offsets[line] < floor) break;
                        if (allLines[line - 1].trim().isEmpty() || startsBlock(allLines[line])) {
                            cut = line;
                            break;
                        }
                    }
                }
                if (cut != null) {
                    end = cut;
                }
            }

            int last = end;
            while (last > start + 1 && allLines[last - 1].trim().isEmpty()) {
                last--;
            }

            StringBuilder body = new StringBuilder();
            for (int i = start; i < last; i++) {
                if (i > start) body.append("\n");
                body.append(allLines[i]);
            }

            pieces.add(new Piece(body.toString(), start + 1, last));
            start = end;
        }
        return pieces;
    }

    private static boolean startsBlock(String line) {
        if (line.isEmpty() || Character.isWhitespace(line.charAt(0))) return false;
        char first = line.charAt(0);
        if ("})];".indexOf(first) >= 0) return false;
        String trimmed = line.trim();
        return !CLOSERS.contains(trimmed);
    }

    private static List<Piece> chunkCells(List<String> cells, int size) {
        List<Piece> pieces = new ArrayList<>();
        int start = 0;
        while (start < cells.size()) {
            StringBuilder body = new StringBuilder();
            int end = start;
            while (end < cells.size() && (body.length() + cells.get(end).length() <= size || end == start)) {
                if (end > start) body.append("\n\n");
                body.append(cells.get(end));
                end++;
            }
            pieces.add(new Piece(body.toString(), start + 1, end));
            start = end;
        }
        return pieces;
    }

    private static List<String> parseNotebookCells(String json) {
        List<String> list = new ArrayList<>();
        try {
            JsonObject root = JsonParser.parseString(json).getAsJsonObject();
            JsonArray cells = root.getAsJsonArray("cells");
            if (cells != null) {
                for (JsonElement el : cells) {
                    JsonObject cell = el.getAsJsonObject();
                    String cellType = cell.has("cell_type") ? cell.get("cell_type").getAsString() : "";
                    if ("code".equals(cellType) || "markdown".equals(cellType)) {
                        StringBuilder cellText = new StringBuilder();
                        JsonElement src = cell.get("source");
                        if (src != null) {
                            if (src.isJsonArray()) {
                                for (JsonElement line : src.getAsJsonArray()) {
                                    cellText.append(line.getAsString());
                                }
                            } else if (src.isJsonPrimitive()) {
                                cellText.append(src.getAsString());
                            }
                        }
                        String t = cellText.toString().trim();
                        if (!t.isEmpty()) list.add(t);
                    }
                }
            }
        } catch (Exception ignored) {}
        return list;
    }

    private static String[] resolvePlace(File file) {
        File current = file.getParentFile();
        File repoRoot = null;
        while (current != null) {
            if (new File(current, ".git").exists()) {
                repoRoot = current;
                break;
            }
            current = current.getParentFile();
        }

        if (repoRoot != null) {
            String repoName = repoRoot.getName();
            String rel = file.getAbsolutePath().substring(repoRoot.getAbsolutePath().length());
            if (rel.startsWith("\\") || rel.startsWith("/")) rel = rel.substring(1);
            rel = rel.replace('\\', '/');
            return new String[]{repoName, repoName + "/" + rel};
        } else {
            return new String[]{null, file.getName()};
        }
    }
}
