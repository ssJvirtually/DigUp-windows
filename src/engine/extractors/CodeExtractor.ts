import fs from 'fs';
import path from 'path';
import { IndexOptions } from '../../shared/types.js';

export interface CodePiece {
  text: string;
  first: number;
  last: number;
}

export interface ExtractedCodeFile {
  pieces: CodePiece[];
  title: string;
  repo: string | null;
  lines: number;
  cells: number | null;
}

export class CodeExtractor {
  public static readonly longestPiece = 4000;

  public static read(filePath: string, options: IndexOptions): ExtractedCodeFile {
    const ext = path.extname(filePath).slice(1).toLowerCase();
    const { repo, title } = this.place(filePath);

    if (ext === 'ipynb') {
      const content = fs.readFileSync(filePath, 'utf8');
      const cells = this.notebookCells(content);
      const text = cells.join('\n');
      if (Buffer.byteLength(text, 'utf8') > options.maxCodeBytes) {
        throw new Error('Notebook cells exceed max code bytes');
      }
      this.check(text, true);
      return {
        pieces: this.cellsToPieces(cells, options.codeStretch),
        title,
        repo,
        lines: this.countLines(text),
        cells: cells.length
      };
    }

    const buffer = fs.readFileSync(filePath);
    // Sniff binary
    if (buffer.subarray(0, 8000).includes(0)) {
      throw new Error('Not text');
    }

    const text = buffer.toString('utf8');
    this.check(text, true);

    return {
      pieces: this.linesToPieces(text, options.codeStretch),
      title,
      repo,
      lines: this.countLines(text),
      cells: null
    };
  }

  public static place(filePath: string): { repo: string | null; title: string } {
    let current = path.dirname(filePath);
    let repoName: string | null = null;
    let repoRoot: string | null = null;

    while (current && current !== path.dirname(current)) {
      if (fs.existsSync(path.join(current, '.git')) || fs.existsSync(path.join(current, 'package.json'))) {
        repoRoot = current;
        repoName = path.basename(current);
        break;
      }
      current = path.dirname(current);
    }

    if (repoRoot && repoName) {
      const rel = path.relative(repoRoot, filePath).replace(/\\/g, '/');
      return { repo: repoName, title: `${repoName}/${rel}` };
    }

    return { repo: null, title: path.basename(filePath) };
  }

  public static check(text: string, isSource: boolean): void {
    if (text.includes('PRIVATE KEY-----')) {
      throw new Error('Holds a private key');
    }
    if (!isSource) return;

    const top = text.slice(0, 1000);
    const generatedMarkers = [
      'DO NOT EDIT',
      '@generated',
      'Code generated by',
      'Autogenerated by',
      'Generated by the protocol'
    ];
    for (const marker of generatedMarkers) {
      if (top.includes(marker)) {
        throw new Error(`Made by a program ("${marker}")`);
      }
    }

    // Minified check
    const lines = Math.max(1, this.countLines(text));
    if (text.length / lines > 300) {
      const allLines = text.split('\n');
      if (allLines.some((l) => l.length > 3000)) {
        throw new Error(`Minified code (${Math.round(text.length / lines)} chars/line)`);
      }
    }
  }

  public static countLines(text: string): number {
    return text.split('\n').length;
  }

  public static linesToPieces(text: string, size = 1800): CodePiece[] {
    const rawLines = text.split(/\r?\n/);
    const count = rawLines.length;

    const offsets: number[] = [0];
    for (const line of rawLines) {
      offsets.push(offsets[offsets.length - 1] + line.length + 1);
    }

    const isBlank = (i: number) => !rawLines[i] || rawLines[i].trim().length === 0;
    const startsBlock = (i: number) => {
      const line = rawLines[i];
      if (!line || /^\s/.test(line)) return false;
      const first = line.trimStart()[0];
      return !'})]'.includes(first);
    };

    const pieces: CodePiece[] = [];
    let start = 0;

    while (start < count) {
      while (start < count && isBlank(start)) start++;
      if (start >= count) break;

      let end = start + 1;
      while (end < count && offsets[end + 1] - offsets[start] <= size) {
        end++;
      }

      let natural = end >= count;
      if (!natural) {
        const floor = offsets[start] + Math.floor((size * 2) / 5);
        let cut: number | null = null;

        for (let line = end; line > start + 1; line--) {
          if (offsets[line] < floor) break;
          if (startsBlock(line) && isBlank(line - 1)) {
            cut = line;
            break;
          }
          if (!cut && (isBlank(line - 1) || startsBlock(line))) {
            cut = line;
          }
        }

        if (cut) {
          end = cut;
          natural = true;
        }
      }

      let last = end;
      while (last > start + 1 && isBlank(last - 1)) last--;

      let body = rawLines.slice(start, last).join('\n');
      if (body.length > this.longestPiece) {
        body = body.slice(0, this.longestPiece);
      }

      pieces.push({
        text: body,
        first: start + 1,
        last
      });

      start = natural ? end : Math.max(end - 2, start + 1);
    }

    return pieces;
  }

  public static notebookCells(jsonString: string): string[] {
    try {
      const nb = JSON.parse(jsonString);
      const cells: string[] = [];
      if (Array.isArray(nb.cells)) {
        for (const cell of nb.cells) {
          if (cell.cell_type === 'code' || cell.cell_type === 'markdown') {
            const source = Array.isArray(cell.source) ? cell.source.join('') : String(cell.source || '');
            if (source.trim().length > 0) {
              cells.push(source.trim());
            }
          }
        }
      }
      return cells;
    } catch {
      return [];
    }
  }

  public static cellsToPieces(cells: string[], size = 1800): CodePiece[] {
    const pieces: CodePiece[] = [];
    let start = 0;

    while (start < cells.length) {
      let end = start + 1;
      let totalLength = cells[start].length;

      while (end < cells.length && totalLength + cells[end].length <= size) {
        totalLength += cells[end].length;
        end++;
      }

      const body = cells.slice(start, end).join('\n\n');
      pieces.push({
        text: body.length > this.longestPiece ? body.slice(0, this.longestPiece) : body,
        first: start + 1,
        last: end
      });

      start = end;
    }

    return pieces;
  }

  public static summary(text: string): string {
    const lines = text.split(/\r?\n/).map((l) => l.trim()).filter((l) => l.length > 0);
    const defLine = lines.find((l) => {
      const words = l.split(/\s+/).slice(0, 4);
      return words.some((w) => ['def', 'class', 'fn', 'function', 'struct', 'enum', 'interface', 'type'].includes(w));
    });
    if (defLine) return defLine;

    const codeLine = lines.find((l) => {
      return !['//', '#', '/*', '*', '--', '"""', 'import ', 'from ', '#include', 'using ', 'package '].some((p) => l.startsWith(p));
    });
    return codeLine || (lines[0] || '');
  }
}
